import React, { useState, useEffect } from 'react';
import { X, RefreshCw, Info } from 'lucide-react';
import { WeddingData, SideType } from '../../types/wedding';

interface CustomLinkModalProps {
  isOpen: boolean;
  activeSide: SideType;
  weddingData: WeddingData;
  onClose: () => void;
  onSaveSlug: (newSlug: string, side: SideType) => void;
}

export const CustomLinkModal: React.FC<CustomLinkModalProps> = ({
  isOpen,
  activeSide,
  weddingData,
  onClose,
  onSaveSlug
}) => {
  const isGroom = activeSide === 'groom';
  
  // Default slugs based on names
  const groomSlugDefault = (weddingData.groomShortName || weddingData.groomName || 'quanghung')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/[^a-z0-9]/g, '');

  const brideSlugDefault = (weddingData.brideShortName || weddingData.brideName || 'minhtue')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/[^a-z0-9]/g, '');

  // Nhà Trai: groom-bride; Nhà Gái: bride-groom
  const autoGeneratedSlug = isGroom
    ? `${groomSlugDefault}-${brideSlugDefault}`
    : `${brideSlugDefault}-${groomSlugDefault}`;

  const currentSlug = isGroom
    ? weddingData.customSlugGroom || autoGeneratedSlug
    : weddingData.customSlugBride || autoGeneratedSlug;

  const [inputSlug, setInputSlug] = useState(currentSlug);

  useEffect(() => {
    if (isOpen) {
      setInputSlug(currentSlug);
    }
  }, [isOpen, currentSlug]);

  if (!isOpen) return null;

  const sanitizeSlug = (val: string) => {
    return val
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/đ/g, 'd')
      .replace(/[^a-z0-9-]/g, '');
  };

  const handleAutoGenerate = () => {
    setInputSlug(autoGeneratedSlug);
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    const finalSlug = sanitizeSlug(inputSlug) || autoGeneratedSlug;
    onSaveSlug(finalSlug, activeSide);
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 bg-black/60 backdrop-blur-xs animate-in fade-in duration-200">
      <div className="bg-white rounded-3xl shadow-2xl border border-stone-200 w-full max-w-md overflow-hidden animate-in zoom-in-95 duration-200">
        
        {/* Header matching Screenshot 1 */}
        <div className="p-5 pb-3 flex items-center justify-between border-b border-stone-100 relative">
          <div className="w-full text-center">
            <h3 className="text-lg font-bold text-stone-900 font-serif">
              Đổi đường link
            </h3>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="p-2 rounded-full bg-stone-100 hover:bg-stone-200 text-stone-500 hover:text-stone-800 transition-colors absolute right-4 top-4"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Body Form matching Screenshot 1 */}
        <form onSubmit={handleSubmit} className="p-5 space-y-4 text-xs font-sans">
          
          {/* Current Link Display */}
          <div>
            <label className="block uppercase font-bold text-stone-400 text-[10px] tracking-wider mb-1">
              LINK HIỆN TẠI
            </label>
            <div className="p-2.5 rounded-xl bg-stone-50 border border-stone-200 text-stone-700 font-mono font-medium text-xs break-all">
              thiepmoionline.khoahoang9999.workers.dev/i/{currentSlug}
            </div>
          </div>

          {/* New Link Input */}
          <div>
            <label className="block uppercase font-bold text-stone-400 text-[10px] tracking-wider mb-1">
              LINK MỚI ({isGroom ? 'NHÀ TRAI' : 'NHÀ GÁI'})
            </label>
            <div className="space-y-1">
              <span className="text-stone-400 text-[11px] font-mono block">
                thiepmoionline.khoahoang9999.workers.dev/i/
              </span>
              <input
                type="text"
                value={inputSlug}
                onChange={(e) => setInputSlug(sanitizeSlug(e.target.value))}
                placeholder="quanghungminhtue"
                className="w-full px-3.5 py-3 rounded-2xl bg-stone-100 border border-stone-200 focus:bg-white focus:ring-2 focus:ring-pink-500 font-mono font-medium text-sm text-stone-900"
              />
            </div>
          </div>

          {/* Auto Generate Button */}
          <div className="flex items-center justify-between text-[11px] pt-1">
            <span className="text-stone-400">
              Chỉ dùng chữ thường, số và dấu gạch ngang
            </span>
            <button
              type="button"
              onClick={handleAutoGenerate}
              className="text-pink-600 hover:text-pink-800 font-bold flex items-center gap-1 cursor-pointer"
            >
              <RefreshCw className="w-3.5 h-3.5" />
              <span>Tạo từ tên cô dâu chú rể</span>
            </button>
          </div>

          {/* Notice Box matching Screenshot 1 */}
          <div className="p-3.5 rounded-2xl bg-stone-100 border border-stone-200 text-stone-600 space-y-1 text-[11px] leading-relaxed flex items-start gap-2.5">
            <Info className="w-4 h-4 text-stone-400 shrink-0 mt-0.5" />
            <p>
              Lưu ý: link cũ vẫn mở được và vẫn dẫn khách tới thiệp của bạn, nên những khách bạn đã gửi link cũ vẫn xem được bình thường.
            </p>
          </div>

          {/* Action Buttons matching Screenshot 1 */}
          <div className="flex items-center justify-end gap-3 pt-3">
            <button
              type="button"
              onClick={onClose}
              className="px-5 py-2.5 text-stone-500 hover:text-stone-800 font-bold text-xs cursor-pointer"
            >
              Hủy
            </button>
            <button
              type="submit"
              className="px-6 py-2.5 rounded-full bg-[#E01460] hover:bg-[#C20E50] text-white font-bold text-xs shadow-md cursor-pointer active:scale-95 transition-all"
            >
              Lưu
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
